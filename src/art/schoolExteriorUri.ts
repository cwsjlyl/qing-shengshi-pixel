export const SCHOOL_EXTERIOR_DATA_URI =
  'data:image/jpeg;base64,' + SCHOOL_EXTERIOR_JPEG_LINES.join('');

let loadingPromise: Promise<boolean> | null = null;

/**
 * 以原生 HTMLImageElement 解碼上傳之學校外觀照片並寫入 Phaser TextureManager
 */
export function loadSchoolExteriorTexture(scene: Phaser.Scene): Promise<boolean> {
  if (scene.textures.exists(SCHOOL_EXTERIOR_KEY)) {
    const tex = scene.textures.get(SCHOOL_EXTERIOR_KEY);
    const src = tex.getSourceImage() as HTMLImageElement | HTMLCanvasElement | undefined;
    if (tex.key !== '__MISSING' && src && src.width >= 160 && src.height >= 100) {
      return Promise.resolve(true);
    }
    scene.textures.remove(SCHOOL_EXTERIOR_KEY);
  }

  if (loadingPromise) return loadingPromise;

  loadingPromise = new Promise<boolean>((resolve) => {
    const img = new Image();
    img.decoding = 'async';
    img.onload = () => {
      loadingPromise = null;
      if (scene.textures.exists(SCHOOL_EXTERIOR_KEY)) {
        scene.textures.remove(SCHOOL_EXTERIOR_KEY);
      }
      const added = scene.textures.addImage(SCHOOL_EXTERIOR_KEY, img);
      added?.setFilter(Phaser.Textures.FilterMode.LINEAR);
      resolve(true);
    };
    img.onerror = () => {
      loadingPromise = null;
      resolve(false);
    };
    img.src = SCHOOL_EXTERIOR_DATA_URI;
  });

  return loadingPromise;
}

export function ensureSchoolExteriorTexture(scene: Phaser.Scene): void {
  void loadSchoolExteriorTexture(scene);
}
